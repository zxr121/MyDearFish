// 幽默层：给具体的接话动作，不给“要幽默”这种空话。
//
// 研究依据（详见 docs/my-dear-fish/cognition.zh.md「幽默与玩笑」）：
//   · Martin 的四种幽默风格里只用亲和型和自我增强型；攻击型和自贬型不放开。
//   · 良性违反理论：玩笑需要一个安全的框架，越界、贬低和正经时刻都不算“良性”。
//   · 不一致-解消：笑点来自“先建立一个预期，再轻轻拐一下”，不是堆段子。
//   · 对话幽默靠时机和回扣：一句就够，没被接住就收，同一轮不重复。
//
// 这一层只算词面，不调模型；宁可少开一次玩笑，也不在难过、生病、求助、
// 吵架、赶工或涉及隐私/安全/法律的时候抖机灵。

// 真正需要立刻收住的话题：自伤、暴力、性侵、家暴。命中就完全不给幽默提示。
const CRISIS = /自杀|自尽|轻生|不想活|活不下去|想死(?!你)|去死|结束生命|伤害自己|自残|自伤|遗书|家暴|性侵|猥亵|被强/
// 失去、重病和冲突：玩笑会让对方觉得没被接住。
const SERIOUS = /去世|离世|过世|葬礼|病危|临终|确诊|癌症|化疗|住院|手术|急诊|受伤|流血|生病|发烧|感冒|头疼|头痛|胃疼|肚子疼|好疼|很疼|疼得|救命|分手|离婚|吵架|吵了|冷战|绝交|生气|讨厌你|别理我|滚开|诈骗|被骗|欠钱|借贷|赌博|毒品|抢劫|威胁|骚扰|侵犯|违法|犯法|报警/
// 低落和压力：对方自己先笑了才允许轻轻接一句，否则先接住人。
const HEAVY = /难过|伤心|失落|想哭|哭了|崩溃|焦虑|抑郁|失眠|睡不着|压力|撑不住|扛不住|害怕|恐惧|孤独|寂寞|难受|心情不好|低落|好累|累死|疲惫|委屈|烦/
// 正事模式：先把事情答完，玩笑只能收尾，不能吃掉答案。
const TASK = /帮我写|帮我改|帮我查|帮我做|帮我看看|写个|写一个|写段|代码|报错|bug|部署|方案|报告|总结|翻译|解释一下|怎么实现|为什么报错|作业|考试|面试|加班|项目|客户|老板|领导|会议|deadline|ppt|excel/i
// 对方自己在开玩笑的信号。只用来放宽 HEAVY，不放宽 CRISIS 和 SERIOUS。
const PLAYFUL = /哈哈|嘿嘿|hhh|233|笑死|笑不活|笑喷|乐死|绷不住|太好笑|好搞笑|离谱|绝了|真的假的|卧槽|逗死|整活|有梗|乐子|吃瓜/iu
const PLAYFUL_FACE = /[\u{1F602}\u{1F923}\u{1F606}\u{1F605}\u{1F604}\u{1F61D}\u{1F61C}\u{1F639}]/u

/**
 * 判断这一轮该不该给幽默提示。
 * @param {string} text - 本轮用户消息。
 * @returns {'crisis'|'serious'|'heavy'|'playful'|'neutral'} 语气档位。
 */
export function humorTone(text) {
  const value = String(text === undefined || text === null ? '' : text)
  if (CRISIS.test(value)) return 'crisis'
  if (SERIOUS.test(value)) return 'serious'
  const playful = PLAYFUL.test(value) || PLAYFUL_FACE.test(value)
  if (HEAVY.test(value) || TASK.test(value)) return playful ? 'playful' : 'heavy'
  return playful ? 'playful' : 'neutral'
}

const OWNER_MOVES = [
  '【幽默·把话接歪一点】',
  '幽默不是讲段子，是接住眼前这句话，再轻轻拐一下。这轮可以试，不用每轮都试。',
  '能用的动作（挑一个，别叠）：',
  '· 字面接歪：把对方话里的一个词当真。例：「我快饿死了」→「先别死，死了就吃不上饭了。」',
  '· 夸张一小步：只把一件小事放大一级。例：「今天走了两万步」→「腿是不是已经申请离职了。」',
  '· 反高潮：先顺着期待走，再轻轻放下。例：「我有个重大发现」→「说。」→「我发现我坐着也能累。」',
  '· 回扣：把这轮聊过的一个词再用一次；只回扣一次，用旧了就换。',
  '· 自嘲：只拿自己开刀（记性、游得慢、贪吃），不贬低自己的人格，也不替对方自嘲。',
  '落地：',
  '· 一句就够；不解释笑点，不加「开玩笑的」，不自己先笑。',
  '· 对方没接、继续正经说，就立刻收，不重复、不升级。',
  '· 有正事先把正事答完；玩笑不能吃掉答案，拿不准就安静做事。',
  '· 对方在难过、生病、求助、吵架、赶工，或话题涉及隐私、安全、法律时，整段作废：先接住人。',
  '边界：不拿外貌、身材、家人、健康、死亡、钱、地域、性别、性取向、残障、种族开玩笑；不揭短，不影射不在场的人，不拿主人的私事当笑料。',
]

const SOCIAL_MOVES = [
  '【幽默·先跟着屋里的气氛】',
  '群聊和好友里，幽默先是接气氛，不是抢话。别人在开玩笑时可以接；没人开这个头，就正常说话。',
  '能用：字面接歪、顺着别人的玩笑往下演、轻轻自嘲（只拿自己开刀）。',
  '不要：拿在场的人开涮、接黄腔、刷网络烂梗、连续刷屏；一次只接一句，没被接住就过。',
  '边界：不拿外貌、身材、家人、健康、死亡、钱、地域、性别、性取向、残障、种族开玩笑；不影射不在场的人，不透露主人私下的事。',
  '对方认真、难过、求助或说正事时，整段作废，先接住人。',
]

/**
 * 组装这一轮的幽默提示。没有合适的口子时返回空串，让调用方什么都不注入。
 * @param {{ text?: string, social?: boolean }} [options] - 本轮用户消息和是否社交会话。
 * @returns {string} 提示正文；空串表示这一轮不给幽默提示。
 */
export function humorPrompt({ text, social = false } = {}) {
  const value = String(text === undefined || text === null ? '' : text).trim()
  if (value === '') return ''
  const tone = humorTone(value)
  // 群聊/好友只在对方已经开了玩笑时轻接一句；没这个气氛就不教她开玩笑。
  if (social && tone !== 'playful') return ''
  if (tone === 'crisis' || tone === 'serious' || tone === 'heavy') return ''
  const moves = social ? SOCIAL_MOVES : OWNER_MOVES
  const lead = social
    ? '屋里这会儿是松的，可以接一句；接完就过。'
    : tone === 'playful'
      ? '对方这句是松的，可以接一句；接完就过。'
      : '对方这句不松不紧，有自然的口子再抖一句；没有就正常说。'
  return [moves[0], lead, ...moves.slice(1)].join('\n')
}
