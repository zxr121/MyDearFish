// 关系十维的纯函数冒烟：原来的五维保留，新增五维从总关系和账目推导。
// 跑法：node tests/关系十维.mjs
import assert from 'node:assert/strict'
import { 十维说明, 十维数, 维阶段 } from '../lib/host.js'

let 挂了 = 0
const 报 = (标签, 过, 详情) => {
  if (!过) 挂了++
  console.log(`${过 ? 'PASS' : 'FAIL'}  ${标签}${详情 ? '  :: ' + 详情 : ''}`)
}
const 夹 = (值) => 值 >= 0 && 值 <= 100

const 默认 = 十维数({ 理解: 20, 尊重: 50, 需要: 20, 自在: 40 }, { 熟: 0, 暖: 50, 信: 50, 张力: 0, 疤: 0, 账: [] }, { 见过: 0 })
报('默认返回十个维度', Object.keys(默认).length === 10 && ['熟悉', '亲近', '互惠', '承诺', '修复'].every((名) => 名 in 默认))
报('十个维度都在 0 到 100', Object.values(默认).every(夹), JSON.stringify(默认))
报('默认熟悉度是 0', 默认.熟悉 === 0, String(默认.熟悉))
报('默认信任直接读总关系', 默认.信任 === 50, String(默认.信任))

const 熟人 = 十维数(
  { 理解: 75, 尊重: 70, 需要: 70, 自在: 75 },
  { 熟: 85, 暖: 78, 信: 80, 张力: 0, 疤: 0, 账: [{ 类: '亲近', 度: 2, 修: '已修' }, { 类: '亲近', 度: 1, 修: '已修' }] },
  { 见过: 60 },
)
报('熟人会抬高熟悉、亲近、互惠、承诺', 熟人.熟悉 > 80 && 熟人.亲近 > 70 && 熟人.互惠 > 55 && 熟人.承诺 > 60, JSON.stringify(熟人))
报('没有冲突时修复不低', 熟人.修复 >= 45 && 维阶段('修复', 熟人.修复) === '还没经过事', String(熟人.修复))

const 伤过 = 十维数(
  { 理解: 60, 尊重: 30, 需要: 55, 自在: 30 },
  {
    熟: 70,
    暖: 38,
    信: 30,
    张力: 50,
    疤: 40,
    账: [
      { 类: '越界', 度: 3, 修: '未修' },
      { 类: '失信', 度: 2, 修: '未修' },
      { 类: '争吵', 度: 2, 修: '再犯' },
    ],
  },
  { 见过: 40 },
)
报('未修和再犯会压低修复与互惠', 伤过.修复 < 40 && 伤过.互惠 < 50, JSON.stringify(伤过))
报('被伤过时亲近不会高', 伤过.亲近 < 60, String(伤过.亲近))

报('阶段话：刚认识/很对等/一碰就碎', 维阶段('熟悉', 10) === '刚认识' && 维阶段('互惠', 80) === '很对等' && 维阶段('修复', 10) === '一碰就碎')
const 说明 = 十维说明(
  { 理解: 75, 尊重: 70, 需要: 70, 自在: 75 },
  { 熟: 85, 暖: 78, 信: 80, 张力: 0, 疤: 0, 账: [] },
  { 见过: 60 },
)
报('说明里十个维度都在', ['理解', '信任', '尊重', '需要', '自在', '熟悉', '亲近', '互惠', '承诺', '修复'].every((名) => 说明.includes(名)), 说明)
报('说明只报阶段不报数字', !/\d/.test(说明), 说明)

assert.equal(挂了, 0)
process.exitCode = 挂了 === 0 ? 0 : 1
