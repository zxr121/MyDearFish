// 风格贴合契约：什么画像在什么关系下该给什么提示；主人永远不收教句长、拆短和连发。
// 跑法：node tests/风格贴合.mjs
// 刷新金样：FISH_UPDATE_EXPECTED=1 node tests/风格贴合.mjs
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const 模 = await import(new URL('../lib/host.js', import.meta.url).href + '?v=' + Date.now())

let 挂了 = 0
const 报 = (标签, 过, 详情) => {
  if (!过) 挂了++
  console.log(`${过 ? 'PASS' : 'FAIL'}  ${标签}${详情 ? '  :: ' + 详情 : ''}`)
}

const 现在 = 1_700_000_000_000
const 一天 = 86_400_000
const 风格 = (补 = {}) => 模.归一风格({ ...模.空风格(), 样本: 48, 句长: 14, ...补 })

const 主人短 = 风格({
  句长: 7, 短句: 0.8, 连发: 0.8, 句号: 0, 叹号: 0,
  语气词: { 呀: 12, 哦: 8 },
})
const 主人长 = 风格({
  句长: 30, 句号: 0.5, 叹号: 0.5, 逗号: 0.6, 表情: 0.4,
})
const 老友短 = 风格({
  句长: 4, 短句: 0.9, 连发: 0.8, 句号: 0, 叹号: 0,
  语气词: { 呀: 12, 啦: 8 },
})
const 朋友长 = 风格({
  句长: 26, 句号: 0.5, 叹号: 0.5, 逗号: 0.6, 省略: 0.4, 表情: 0.4, 网络词: 0.3,
  摘要: '爱用短句，常用哈哈', 摘要At: 现在 - 一天, 摘要样本: 20,
})
const 熟人组 = 风格({
  句长: 10, 短句: 0.7, 句号: 0, 叹号: 0, 连发: 0.8, 问句: 0.5,
  语气词: { 呀: 12, 哦: 8 },
})

const 主人禁句 = /多拆成短句|拆成两三条|几个字就停|句子可以短|别只回几个字|可以多说两句/
const 护栏 = '把想说的说完整'

// ---------- 主人：永远不教句长、拆短和连发 ----------
const 主人短提示 = 模.拼风格贴合(主人短, { 名: '主人', 阶段: '老友', 主人: true, now: 现在 })
报('主人·短画像：给了标点和口气提示', 主人短提示.includes('说话节奏') && 主人短提示.includes('句号'), 主人短提示)
报('主人·短画像：不教句长、拆短和连发', !主人禁句.test(主人短提示), 主人短提示)
报('主人·短画像：写明句子长短照自己来', 主人短提示.includes(护栏) && 主人短提示.includes('不是把话截短'), 主人短提示)
const 主人长提示 = 模.拼风格贴合(主人长, { 名: '主人', 阶段: '老友', 主人: true, now: 现在 })
报('主人·长画像：也不劝多说两句', !主人禁句.test(主人长提示), 主人长提示)
报('主人·长画像：照样带完整性护栏', 主人长提示.includes(护栏), 主人长提示)
for (const 样本 of [0, 5]) {
  for (const 主人 of [true, false]) {
    const 提示 = 模.拼风格贴合(风格({ ...主人短, 样本 }), {
      名: '阿明', 阶段: '老友', 主人, now: 现在,
    })
    报(`${主人 ? '主人' : '老友'}·样本 ${样本}：不到 6 条不贴合`, 提示 === '', 提示)
  }
}
const 样本六 = 模.拼风格贴合(风格({ ...主人短, 样本: 6 }), { 名: '主人', 阶段: '老友', 主人: true, now: 现在 })
报('主人·样本 6：刚好过门槛就贴合，且带护栏', 样本六 !== '' && 样本六.includes(护栏), 样本六)
const 样本二十四 = 模.拼风格贴合(风格({ ...主人短, 样本: 24 }), { 名: '主人', 阶段: '老友', 主人: true, now: 现在 })
报('主人·样本 24：力度满格但内容不变', 样本二十四 !== '' && !主人禁句.test(样本二十四) && 样本二十四.includes(护栏), 样本二十四)

// ---------- 非主人：短画像可以说短，但必须带完整性 ----------
const 老友短提示 = 模.拼风格贴合(老友短, { 名: '阿明', 阶段: '老友', now: 现在 })
报('老友·短画像：可以说短，但要把意思说完整', 老友短提示.includes('句子可以短') && 老友短提示.includes('把意思说完整'), 老友短提示)
const 连发画像 = 风格({ 句长: 12, 短句: 0.8, 连发: 0.8, 句号: 0.5, 叹号: 0.5 })
const 连发提示 = 模.拼风格贴合(连发画像, { 名: '阿明', 阶段: '老友', now: 现在 })
报('老友·私聊：对方爱连发就跟着连发', 连发提示.includes('拆成两三条'), 连发提示)
const 熟人组提示 = 模.拼风格贴合(熟人组, { 名: '阿明', 阶段: '熟人', 群: true, now: 现在 })
报('群里不按某个人带语气词和反问', !熟人组提示.includes('呀') && !熟人组提示.includes('哦') && !熟人组提示.includes('反问'), 熟人组提示)
const 群连发提示 = 模.拼风格贴合(连发画像, { 名: '阿明', 阶段: '熟人', 群: true, now: 现在 })
报('群里不跟着某个人连发', !群连发提示.includes('拆成两三条'), 群连发提示)
报('群里保留少句号和轻贴合护栏', 熟人组提示.includes('句号') && 熟人组提示.includes('群里人杂'), 熟人组提示)
const 熟人短 = 风格({ ...老友短, 句长: 8 })
const 熟人组短提示 = 模.拼风格贴合(熟人短, { 名: '阿明', 阶段: '熟人', 群: true, now: 现在 })
报('群里短画像也只说“短但完整”，不教截短', 熟人组短提示.includes('句子可以短') && 熟人组短提示.includes('把意思说完整'), 熟人组短提示)

// ---------- 关系门槛、张力、别学 ----------
报('生人不贴合', 模.拼风格贴合(老友短, { 名: '阿明', 阶段: '生人', now: 现在 }) === '')
报('眼熟·成熟画像给最轻的一档', 模.拼风格贴合(老友短, { 名: '阿明', 阶段: '眼熟', now: 现在 }) !== '')
报('张力 60：完全不贴合', 模.拼风格贴合(老友短, { 名: '阿明', 阶段: '老友', 张力: 60, now: 现在 }) === '')
const 张力零 = 模.拼风格贴合(老友短, { 名: '阿明', 阶段: '老友', 张力: 0, now: 现在 })
const 张力三十 = 模.拼风格贴合(老友短, { 名: '阿明', 阶段: '老友', 张力: 30, now: 现在 })
报('张力 30：还贴合，但只留最重的一条', 张力三十 !== '' && 张力三十.length < 张力零.length, `${张力零.length} → ${张力三十.length}`)
const 主人张力三十 = 模.拼风格贴合(主人短, { 名: '主人', 阶段: '老友', 主人: true, 张力: 30, now: 现在 })
报('主人张力 30：提示变短，完整性护栏仍在', 主人张力三十.includes(护栏) && !主人禁句.test(主人张力三十), 主人张力三十)
报('别学：完全不贴合', 模.拼风格贴合({ ...老友短, 别学: true }, { 名: '阿明', 阶段: '老友', now: 现在 }) === '')

// ---------- 标点和摘要 ----------
const 有句号 = 风格({ ...老友短, 句号: 0.5, 叹号: 0.5 })
报('对方打句号：不再教少打句号', !模.拼风格贴合(有句号, { 名: '阿明', 阶段: '老友', now: 现在 }).includes('少打句号'))
const 有摘要 = 模.拼风格贴合(朋友长, { 名: '小鱼', 阶段: '朋友', now: 现在 })
报('非主人：新鲜摘要写进提示', 有摘要.includes('对方打字爱用短句，常用哈哈'), 有摘要)
const 主人摘要 = 模.拼风格贴合({ ...朋友长, 摘要: '爱用短句' }, { 名: '主人', 阶段: '老友', 主人: true, now: 现在 })
报('主人：摘要不进提示，免得更像对方', !主人摘要.includes('对方打字'), 主人摘要)
const 旧摘要 = 模.拼风格贴合({ ...朋友长, 摘要At: 现在 - 130 * 一天 }, { 名: '小鱼', 阶段: '朋友', now: 现在 })
报('摘要超过 120 天：不再带', !旧摘要.includes('对方打字'), 旧摘要)

// ---------- 金样：六个代表场景整段对比 ----------
const 场景 = {
  'owner-short': { 画像: 主人短, 况: { 名: '主人', 阶段: '老友', 主人: true, now: 现在 } },
  'owner-long': { 画像: 主人长, 况: { 名: '主人', 阶段: '老友', 主人: true, now: 现在 } },
  'friend-short': { 画像: 老友短, 况: { 名: '阿明', 阶段: '老友', now: 现在 } },
  'friend-long-summary': { 画像: 朋友长, 况: { 名: '小鱼', 阶段: '朋友', now: 现在 } },
  'acquaintance-group': { 画像: 熟人组, 况: { 名: '阿明', 阶段: '熟人', 群: true, now: 现在 } },
  'friend-tension-30': { 画像: 老友短, 况: { 名: '阿明', 阶段: '老友', 张力: 30, now: 现在 } },
}
const 金样路径 = fileURLToPath(new URL('./expected/style-hints.json', import.meta.url))
const 实际金样 = {}
for (const [键, { 画像, 况 }] of Object.entries(场景)) {
  实际金样[键] = 模.拼风格贴合(画像, 况)
}
if (process.env.FISH_UPDATE_EXPECTED === '1') {
  mkdirSync(dirname(金样路径), { recursive: true })
  writeFileSync(金样路径, `${JSON.stringify(实际金样, null, 2)}\n`, 'utf8')
  console.log(`已刷新金样：${金样路径}`)
} else {
  const 期望 = existsSync(金样路径) ? JSON.parse(readFileSync(金样路径, 'utf8')) : {}
  for (const [键, 文本] of Object.entries(实际金样)) {
    报(`金样·${键}`, 期望[键] === 文本, 期望[键] === 文本 ? '' : `\n期望：${期望[键] ?? '(缺)'}\n实际：${文本}`)
  }
}

if (挂了 > 0) {
  console.error(`\n有 ${挂了} 条没过 ❌`)
  process.exit(1)
}
console.log('\n全部通过 ✅')
