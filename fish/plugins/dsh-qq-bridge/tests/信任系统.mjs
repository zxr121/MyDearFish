// 「收藏权限」信任层与收藏指令解析的纯函数测试。
// 跑法： node tests/信任系统.mjs

import {
  评估信任, 归一信任规则, 信任概况, 信任默认规则,
} from '../lib/trust.js'
import {
  解析存表情要求, 解析改备注要求, 净收藏备注,
} from '../lib/sticker-commands.js'

let 挂了 = 0
const 报 = (标签, 过, 详情) => { if (!过) 挂了++; console.log(`${过 ? 'PASS' : 'FAIL'}  ${标签}${详情 ? '  :: ' + 详情 : ''}`) }

const 现在 = Date.now()
const 好人 = {
  号: '111',
  名: '小甲',
  账号: [{ 号: '111' }, { 号: '222' }],
  主人: false,
  天数: ['2026-10-30', '2026-10-31', '2026-11-01'],
  初见At: 现在 - 5 * 86_400_000,
  见过: 40,
  关系: { 熟: 30, 信: 60, 互动: 5, 见过: 40, 疤: 0, 张力: 5 },
}
const 新人 = {
  号: '333',
  名: '小乙',
  账号: [{ 号: '333' }],
  主人: false,
  天数: ['2026-11-03'],
  初见At: 现在 - 3_600_000,
  见过: 2,
  关系: { 熟: 0.4, 信: 50, 互动: 0, 见过: 2, 疤: 0, 张力: 0 },
}
const 有疤 = {
  ...好人,
  号: '444',
  名: '小丙',
  关系: { 熟: 70, 信: 40, 互动: 9, 见过: 90, 疤: 30, 张力: 70 },
}

报('信任：主人永远可以，不需要人物记录', (() => {
  const 信 = 评估信任(null, {}, { 主人: true })
  return 信.级别 === '主人' && 信.能收藏 === true
})())

报('信任：自动达标的人可以动收藏', (() => {
  const 信 = 评估信任(好人, {}, { now: 现在 })
  return 信.级别 === '受信' && 信.能收藏 === true && 信.自动 === true && 信.差.length === 0
})(), JSON.stringify(评估信任(好人, {}, { now: 现在 })))

报('信任：新人还不够自动受信，差在哪里说得清', (() => {
  const 信 = 评估信任(新人, {}, { now: 现在 })
  return 信.级别 === '普通' && 信.能收藏 === false && 信.差.some((x) => x.includes('消息')) && 信.差.some((x) => x.includes('天'))
})(), JSON.stringify(评估信任(新人, {}, { now: 现在 }).差))

报('信任：疤和张力高会被按住', (() => {
  const 信 = 评估信任(有疤, {}, { now: 现在 })
  return 信.级别 === '普通' && 信.差.some((x) => x.includes('疤')) && 信.差.some((x) => x.includes('张力'))
})(), JSON.stringify(评估信任(有疤, {}, { now: 现在 }).差))

报('信任：手动加白可以跨过自动门槛，认小号也行', (() => {
  const 信 = 评估信任(新人, { 手动加: ['222'] }, { now: 现在, 号: '222' })
  return 信.级别 === '受信' && 信.能收藏 === true && 信.手动 === '加'
})())

报('信任：手动收回优先于自动达标和手动加白', (() => {
  const 信 = 评估信任(好人, { 手动加: ['111'], 手动禁: ['222'] }, { now: 现在 })
  return 信.级别 === '普通' && 信.能收藏 === false && 信.手动 === '禁'
})())

报('信任：自动受信关掉后只有手动名单有效', (() => {
  const 关 = 评估信任(好人, { 自动: false }, { now: 现在 })
  const 手 = 评估信任(好人, { 自动: false, 手动加: ['111'] }, { now: 现在 })
  return 关.能收藏 === false && 手.能收藏 === true
})())

报('信任：没见过的号是生人，不是受信', 评估信任(null, {}, { 号: '999' }).级别 === '生人')
报('信任：规则归一化会去重、限制范围、禁优先', (() => {
  const 规 = 归一信任规则({
    自动: true,
    手动加: ['111', '111', '222'],
    手动禁: ['222'],
    最少天数: 99,
    最少见过: -3,
    最少熟: 200,
    最多疤: -1,
  })
  return JSON.stringify(规.手动加) === '["111"]' && 规.手动禁.length === 1 &&
    规.最少天数 === 30 && 规.最少见过 === 0 && 规.最少熟 === 100 && 规.最多疤 === 0
})(), JSON.stringify(归一信任规则({ 手动加: ['111', '111', '222'], 手动禁: ['222'], 最少天数: 99, 最少见过: -3, 最少熟: 200, 最多疤: -1 })))

报('信任概况：数出受信、自动、手动和禁止人数', (() => {
  const 概 = 信任概况([好人, 新人, 有疤], { 手动加: ['333'], 手动禁: ['444'] }, '999')
  return 概.受信数 === 2 && 概.自动受信数 === 1 && 概.手动加数 === 1 && 概.手动禁数 === 1 && 概.受信.some((x) => x.号 === '333' && x.手动 === '加')
})(), JSON.stringify(信任概况([好人, 新人, 有疤], { 手动加: ['333'], 手动禁: ['444'] }, '999')))

报('信任默认规则：自动开，门槛是 3 天 / 25 条 / 3 次互动', 信任默认规则.自动 === true && 信任默认规则.最少天数 === 3 && 信任默认规则.最少见过 === 25 && 信任默认规则.最少互动 === 3)

// ---------- 存表情：自然语言 ----------
const 存样本 = [
  ['这个绿毛的表情存下来，回头发给我', true, ''],
  ['存这个，备注叫无语', true, '无语'],
  ['这个也存一下', true, ''],
  ['存下来，名字叫小蓝', true, '小蓝'],
  ['存这个，我名字叫小明', true, ''],
  ['这张存了，标签：搞笑', true, '搞笑'],
  ['存下来叫什么呢', true, ''],
  ['收藏下表情包', true, ''],
  ['你保存下这几个', true, ''],
  ['把这张存了，名字你来取', true, ''],
  ['今天食堂好难吃', false, ''],
  ['我存了', false, ''],
]
for (const [文, 要存, 备注] of 存样本) {
  const 果 = 解析存表情要求(文)
  报('存表情解析：' + 文, 果.要存 === 要存 && 果.备注 === 备注, JSON.stringify(果))
}

// ---------- 改备注：目标与名字 ----------
const 改样本 = [
  ['把 #3 的备注改成无语', 3, '', '无语'],
  ['第3张表情改名叫小蓝', 3, '', '小蓝'],
  ['把刚才那张表情的备注改成“无语”吧', 0, '刚才那张', '无语'],
  ['3号表情备注改成无语', 3, '', '无语'],
  ['第5个改叫“小鲸鱼”', 5, '', '小鲸鱼'],
  ['这张改名叫无语', 0, '这张', '无语'],
  ['把 #7 的标签写成 笑死', 7, '', '笑死'],
]
for (const [文, 号, 词, 名] of 改样本) {
  const 果 = 解析改备注要求(文)
  报('改备注解析：' + 文, !!果 && 果.目标号 === 号 && 果.目标词 === 词 && 果.新备注 === 名, JSON.stringify(果))
}
const 改不认 = [
  '把群备注改成小明',
  '把我给你的备注改一下',
  '把 #3 的表情改一下',
  '我的备注改了吗',
  '把这张的备注改成什么呢',
  '今天食堂好难吃',
]
for (const 文 of 改不认) {
  报('改备注不误伤：' + 文, 解析改备注要求(文) === null, JSON.stringify(解析改备注要求(文)))
}

报('备注清洗：去引号、开头连接词和结尾语气词，太泛的不算名字', (() => {
  const 样本 = ['“小蓝”', '备注叫小蓝', '名字叫无语吧', '什么名字', '受信让存2', '', '   ']
  const 期望 = ['小蓝', '小蓝', '无语', '', '', '', '']
  return JSON.stringify(样本.map(净收藏备注)) === JSON.stringify(期望)
})(), JSON.stringify(['“小蓝”', '备注叫小蓝', '名字叫无语吧', '什么名字', '受信让存2', '', '   '].map(净收藏备注)))

if (挂了 > 0) {
  console.error(`\n信任与收藏指令测试没全过：${挂了} 条 ❌`)
  process.exit(1)
}
