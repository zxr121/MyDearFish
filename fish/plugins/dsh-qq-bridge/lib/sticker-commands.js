// 从聊天里认出“存这张表情”“把 #3 的备注改成……”。
//
// 只做解析，不碰 QQ、不碰收藏：调用方先判断说话人受不受信，再决定落不落地。
// 这里也不看上下文，不替人猜“这张”是哪张；目标不在话里就留给调用方去问。

const 存动作 = /(?:收藏|保存|存)(?:一下|下来|起来|下|个|这个|这张|它|图|表情)/u
const 存前置 = /(?:这张|这个(?:表情)?|它|图)[，, ]*(?:存|收藏|保存)(?:了|吧|一下|下来|起来)?/u
const 存短句 = /^(?:存|收藏|保存|收下)(?:吧|了|下)?[。！!？?]*$/u
const 备注值 = '([^”"」』\\n，,。；;！!？?]{1,30})'
const 明确备注 = new RegExp(`(?:备注|备注名|标签)\\s*${'(?:就|要|是|为|叫|改成|换成|设成|写成|写作|改为|换为|设为|取名为|命名为)?'}\\s*[：:]?\\s*[“"「『]?${备注值}`, 'u')
const 改备注词 = new RegExp(`(?:备注|备注名|名字|标签)\\s*(?:改成|换成|设成|写成|改为|换为|设为|更正为|更正成|纠正为|纠正成|修正为|修正成|改正为|改正成|修改为|修改成|写作|叫|是|为|[:：])\\s*[“"「『]?${备注值}`, 'u')
const 改叫 = new RegExp(`(?:改名叫|改叫|改名为|改名成|重命名为|更正为|更正成|纠正为|纠正成|修正为|修正成|改正为|改正成|修改为|修改成|名叫|命名为|改成|换成|设成|写成)\\s*[“"「『]?${备注值}`, 'u')
const 泛备注 = new Set([
  '表情', '表情包', '这个', '这张', '这张图', '图', '它', '一下', '下来', '起来',
  '这个表情', '这张表情', '刚才那张', '刚那张', '未命名', '受信让存', '主人让存', '备注',
])

/** 备注只留短名：去引号、括号、开头连接词和结尾语气词；太泛的不算名字。 */
export function 净收藏备注(值) {
  let 名 = String(值 === undefined || 值 === null ? '' : 值)
    .replace(/[“”"「」『』【】\[\]（）()<>《》]/g, ' ')
    .replace(/^(?:备注(?:名|名字|标签)?|标签|名字)?\s*(?:[:：]|就|要|是|为|叫|改成|换成|设成|写成|写作|改为|换为|设为|取名为|命名为|成|作)+/u, '')
    .replace(/[，,。.；;！!？?~～…\s]+$/u, '')
    .replace(/(?:吧|啊|呀|哦|嘛|捏|哈|啦|喽|哒|呗)+$/u, '')
    .replace(/\s+/g, ' ')
    .trim()
  if (名.length > 24) 名 = 名.slice(0, 24).trim()
  if (名 === '' || 泛备注.has(名) || /^(?:受信|主人)让存\d*$/u.test(名)) return ''
  if (/^(?:什么|啥|哪个|哪张|随便|你定|你取|你来|帮我|给我|取个|起个|想个|想一个|怎么)/u.test(名)) return ''
  if (/[\u0000-\u001f\u007f]/u.test(名)) return ''
  return 名
}

/** 中文数字只认 1–99，够指收藏编号就行。 */
function 中文数(值) {
  const 文 = String(值 || '')
  if (/^\d+$/.test(文)) return Number(文)
  const 字 = { 一: 1, 二: 2, 三: 3, 四: 4, 五: 5, 六: 6, 七: 7, 八: 8, 九: 9 }
  if (文 === '十') return 10
  if (文.includes('十')) {
    const [十前, 十后] = 文.split('十')
    return (十前 === '' ? 1 : 字[十前] || 0) * 10 + (十后 === '' ? 0 : 字[十后] || 0)
  }
  return 字[文] || 0
}

/**
 * 这句话是不是在让她把表情存下来；顺手取出备注名。
 * @param {unknown} 文字 - 对方说的话。
 * @returns {{要存: boolean, 备注: string}} `备注` 为空串表示没指定名字。
 */
export function 解析存表情要求(文字) {
  const 原文 = String(文字 === undefined || 文字 === null ? '' : 文字)
  const 平 = 原文.replace(/\s+/g, '')
  if (平 === '') return { 要存: false, 备注: '' }
  const 要存 = 存动作.test(平) || 存前置.test(平) || 存短句.test(平)
  if (!要存) return { 要存: false, 备注: '' }
  let 备注 = ''
  const 明确 = 明确备注.exec(原文)
  if (明确) 备注 = 净收藏备注(明确[1])
  if (备注 === '') {
    const 起 = 原文.search(/(?:收藏|保存|存)/u)
    const 尾 = 起 >= 0 ? 原文.slice(起) : 原文
    if (!/(?:我|你|他|她|它|人)名字/u.test(尾)) {
      const 叫 = /(?:名字|名|叫|取名(?:为|叫)?|命名为)\s*[“"「『]?([^”"」』\n，,。；;！!？?]{1,30})/u.exec(尾)
      if (叫) 备注 = 净收藏备注(叫[1])
    }
  }
  return { 要存: true, 备注 }
}

const 改备注问题 = /(?:改(?:了|过|好|完|成)?[吗么没]|改没改|改好没|改成什么|改什么|怎么改|为什么改|要不要改|用不用改|别改|不用改|不要改|没改|还没改|改不改|备注(?:是|叫|写)?什么)/u
const 改备注动词 = /(?:改|换|设|写|重命名|命名|更正|纠正|修正|改正|修改|调整)/u
const 表情目标 = /(?:#\s*\d+|第\s*[0-9一二三四五六七八九十]{1,3}\s*[张个号]|(?:这|那)(?:张|个)?(?:表情|贴纸))/u

/**
 * 这句话像不像在让她改自己收藏表情的备注；只判意图，不猜是哪张、也不猜叫什么。
 * @param {unknown} 文字 - 对方说的话。
 * @returns {boolean} 像改备注请求时为 true；群备注、好友备注、疑问和否定句为 false。
 */
export function 像改备注要求(文字) {
  const 平 = String(文字 === undefined || 文字 === null ? '' : 文字).replace(/\s+/g, '')
  if (平 === '') return false
  if (/(?:群备注|群名片|好友备注|联系人|名片)/u.test(平)) return false
  if (/(?:吗|嘛|有没有|是否)/u.test(平)) return false
  if (改备注问题.test(平)) return false
  if (!改备注动词.test(平)) return false
  if (/(?:备注|标签)/u.test(平)) return true
  return 表情目标.test(平) && /(?:表情|贴纸|收藏)/u.test(平)
}

/**
 * 这句话是不是在让她改已有收藏表情的备注。
 * @param {unknown} 文字 - 对方说的话。
 * @returns {{目标号: number, 目标词: string, 新备注: string}|null} 目标号 0 表示用“这张/那张”指代；不像改备注时返回 null。
 */
export function 解析改备注要求(文字) {
  const 原文 = String(文字 === undefined || 文字 === null ? '' : 文字)
  if (原文.trim() === '') return null
  if (!/(?:备注|备注名|名字|标签|改叫|改名|名叫|命名)/u.test(原文)) return null
  if (!/(?:改|换|设|写|重命名|叫|命名|更正|纠正|修正|改正|修改)/u.test(原文)) return null
  if (/(?:群备注|群名片|好友备注|联系人|名片)/u.test(原文)) return null
  let 目标号 = 0
  let 目标词 = ''
  let m = /#\s*(\d{1,3})/u.exec(原文)
  if (m) 目标号 = Number(m[1])
  if (目标号 === 0) {
    m = /第\s*([0-9一二三四五六七八九十]{1,3})\s*(?:张|个|号)?/u.exec(原文)
    if (m) 目标号 = 中文数(m[1])
  }
  if (目标号 === 0) {
    m = /(?:^|[^\d])(\d{1,3})\s*(?:号|张)/u.exec(原文)
    if (m) 目标号 = Number(m[1])
  }
  if (目标号 === 0) {
    m = /(这张|那张|刚才那张|刚那张|这张表情|这个表情)/u.exec(原文)
    if (m) 目标词 = m[1]
  }
  if (目标号 === 0 && 目标词 === '') return null
  const 匹配 = 改备注词.exec(原文) || 改叫.exec(原文)
  const 新备注 = 净收藏备注(匹配 && 匹配[1])
  if (新备注 === '') return null
  return { 目标号, 目标词, 新备注 }
}
